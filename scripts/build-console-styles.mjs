#!/usr/bin/env node
/**
 * Compile the console SCSS subset into CSS and a TS string module.
 *
 * The runtime must not read files: the bundled CLI has no guarantee that the
 * stylesheet sits next to the bundle. Keeping the compiled CSS in a generated
 * TS module makes the same stylesheet available to source runs and bundles.
 *
 * Supported SCSS subset: comments and top-level `$variables`. Nesting/mixins
 * are intentionally rejected so the output stays easy to audit.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'packages/components/console/styles/console.scss');
const cssTarget = path.join(root, 'packages/components/console/styles/console.css');
const tsTarget = path.join(root, 'packages/components/console/src/default-styles.generated.ts');

let scss = await readFile(source, 'utf8');
scss = scss.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
const variables = new Map();
scss = scss.replace(/^\s*\$([\w-]+)\s*:\s*([^;]+);\s*$/gm, (_match, name, value) => {
    variables.set(name, value.trim());
    return '';
});
for (let depth = 0; depth < 8; depth++) {
    scss = scss.replace(/\$([\w-]+)/g, (match, name) => variables.get(name) ?? match);
}
if (/\$[\w-]+/.test(scss)) {
    throw new Error('console.scss: unresolved variables');
}
const css = `/* Compiled from console.scss by scripts/build-console-styles.mjs. Do not edit. */\n${scss.trim()}\n`;
await writeFile(cssTarget, css);
const content = `/** Generated by scripts/build-console-styles.mjs. Do not edit. */\nexport const DEFAULT_CONSOLE_STYLESHEET = ${JSON.stringify(css)};\n`;
await writeFile(tsTarget, content);
console.log(`console styles: ${source} -> ${cssTarget} -> ${tsTarget}`);
