#!/usr/bin/env node
/**
 * Compile the console stylesheet into a TS string module.
 *
 * The runtime must not read files: the bundled CLI has no guarantee that the
 * stylesheet sits next to the bundle. Keeping the compiled CSS in a generated
 * TS module makes the same stylesheet available to source runs and bundles.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'packages/components/console/styles/console.css');
const target = path.join(root, 'packages/components/console/src/default-styles.generated.ts');
const css = await readFile(source, 'utf8');
const content = `/** Generated by scripts/build-console-styles.mjs. Do not edit. */\nexport const DEFAULT_CONSOLE_STYLESHEET = ${JSON.stringify(css)};\n`;
await writeFile(target, content);
console.log(`console styles: ${source} -> ${target}`);
