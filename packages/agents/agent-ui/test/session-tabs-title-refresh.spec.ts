import expect = require('expect');
import { Suite, Test } from '@tsdi/unit';
import { AgentConsoleSessionTabsSource } from '../src/AgentConsoleSessionTabsSource';
import { createConsole, RuntimeStub, SchedulerStub, SessionServiceStub } from './_helpers';

@Suite('console session tab titles')
export class SessionTabTitleTest {
    @Test('a completed turn refreshes the tab title generated by the runtime')
    async turnCompletionRefreshesTabTitle() {
        const runtime = new RuntimeStub();
        const sessions = new SessionServiceStub(runtime);
        // The runtime titles the session when the first user message lands; the
        // console's session snapshot is stale until it refreshes.
        sessions.listProjectSessions = async () => [];
        sessions.listSessions = async () => [{
            id: 'console',
            current: true,
            title: '创建 sleep-score 项目',
            lastActiveAt: 2
        } as any];
        const component = createConsole(runtime, new SchedulerStub(), undefined, undefined, undefined, undefined, sessions);
        await component.onInit();
        try {
            const state = component.sessionState;
            state.setMessageLayout('viewport');
            state.setSessions([{ id: 'console', current: true } as any]);

            const tabsBefore = new AgentConsoleSessionTabsSource(state).items;
            expect(tabsBefore[0]?.label).toContain('New session');

            state.setInput('hi');
            await (component as any).submit();
            // The refresh is fire-and-forget after the turn settles.
            await new Promise(resolve => setTimeout(resolve, 20));

            expect(state.sessions[0]?.title).toEqual('创建 sleep-score 项目');
            const tabsAfter = new AgentConsoleSessionTabsSource(state).items;
            expect(tabsAfter[0]?.label).toContain('创建 sleep-score 项目');
            expect(tabsAfter[0]?.label).not.toContain('New session');
        } finally {
            component.onDestroy();
        }
    }
}
