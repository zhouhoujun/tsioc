export function adminMessage(locale: AdminLocale, key: string, params?: Record<string, unknown>): string {
    const template = MESSAGES[locale]?.[key] ?? MESSAGES.en[key] ?? key;
    return params
        ? template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`))
        : template;
}
